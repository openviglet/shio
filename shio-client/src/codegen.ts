/**
 * TypeScript code generation from Shio post-type schemas (SH11).
 *
 * Pure and dependency-free: it turns the {@link ShioPostTypeSchema}[] returned by
 * {@link ShioClient.getPostTypes} into a `.d.ts` source string. The `shio-types`
 * CLI ({@link file:../bin/shio-types.mjs}) wires the fetch + file write around it;
 * keeping the transform pure makes it testable without a network or a filesystem.
 */
import type { ShioFieldSchema, ShioPostTypeSchema } from "./types";

/** Options for {@link generateShioTypes}. */
export interface GenerateTypesOptions {
  /**
   * The module the generated `Post` interfaces import `ShioPost` from. Defaults
   * to the published package name; set to a relative path when generating into
   * the SDK's own source tree.
   */
  importFrom?: string;
  /** Override the file banner comment (e.g. to pin a version). */
  banner?: string;
}

const DEFAULT_IMPORT = "@viglet/shio-client";
const DEFAULT_BANNER =
  "// AUTO-GENERATED by @viglet/shio-client (shio-types). DO NOT EDIT BY HAND.\n" +
  "// Re-run `shio-types` after changing a post-type.";

/**
 * Generate `.d.ts` source declaring one typed `Post` interface per post-type,
 * plus a `ShioPostTypes` name→type map. Page code then gets autocomplete on
 * `post.attrs.*`.
 *
 * @example
 * const schemas = await client.getPostTypes();
 * await writeFile("shio-types.d.ts", generateShioTypes(schemas));
 */
export function generateShioTypes(
  schemas: ShioPostTypeSchema[],
  options: GenerateTypesOptions = {}
): string {
  const importFrom = options.importFrom ?? DEFAULT_IMPORT;
  const banner = options.banner ?? DEFAULT_BANNER;

  // Sort for deterministic output regardless of server ordering.
  const sorted = [...schemas].sort((a, b) => a.name.localeCompare(b.name));

  // Resolve a unique, valid PascalCase identifier per post-type name.
  const ifaceByName = new Map<string, string>();
  const used = new Set<string>();
  for (const pt of sorted) {
    let base = pascalCase(pt.name) || "PostType";
    let candidate = base;
    let n = 2;
    while (used.has(candidate)) candidate = `${base}${n++}`;
    used.add(candidate);
    ifaceByName.set(pt.name, candidate);
  }

  const blocks: string[] = [];
  for (const pt of sorted) {
    const iface = ifaceByName.get(pt.name)!;
    const doc = docComment(pt.title ?? pt.description, 0);
    // An intersection (not `interface extends`): `ShioPost.attrs` is
    // `Record<string, unknown>`, and an interface is not assignable to that, so
    // `extends` would be a type error (TS2430). The intersection narrows
    // `postType` to the literal and merges the typed `attrs` while staying a
    // subtype of `ShioPost`.
    blocks.push(
      `${doc}export interface ${iface}Attrs {\n${renderFields(pt.fields, 1)}}\n\n` +
        `/** A \`${pt.name}\` post with typed attributes. */\n` +
        `export type ${iface}Post = ShioPost & {\n` +
        `  postType: ${JSON.stringify(pt.name)};\n` +
        `  attrs: ${iface}Attrs;\n` +
        `};`
    );
  }

  const mapEntries = sorted
    .map((pt) => `  ${propKey(pt.name)}: ${ifaceByName.get(pt.name)}Post;`)
    .join("\n");

  const map =
    "/** Maps each post-type's API name to its typed post interface. */\n" +
    `export interface ShioPostTypes {\n${mapEntries || ""}\n}\n\n` +
    "/** Union of all known post-type API names. */\n" +
    "export type ShioPostTypeName = keyof ShioPostTypes;";

  return (
    `${banner}\n\n` +
    `import type { ShioPost } from ${JSON.stringify(importFrom)};\n\n` +
    (blocks.length ? `${blocks.join("\n\n")}\n\n` : "") +
    `${map}\n`
  );
}

/** Render the body lines of an `Attrs` interface (one field per line). */
function renderFields(fields: ShioFieldSchema[], depth: number): string {
  const pad = "  ".repeat(depth);
  return [...fields]
    .sort((a, b) => a.ordinal - b.ordinal)
    .map((f) => {
      const doc = docComment(f.label ?? f.description, depth);
      const optional = f.required ? "" : "?";
      return `${doc}${pad}${propKey(f.name)}${optional}: ${fieldType(f, depth)};\n`;
    })
    .join("");
}

/** Map a schema field to its TypeScript type. */
function fieldType(field: ShioFieldSchema, depth: number): string {
  if (field.fields && field.fields.length > 0) {
    // Relator: an array of objects shaped by the sub-fields (inlined).
    const inner = renderFields(field.fields, depth + 1);
    const pad = "  ".repeat(depth);
    return `Array<{\n${inner}${pad}}>`;
  }
  if (field.multiple) {
    return "string[]";
  }
  return "string";
}

/** A leading JSDoc comment line for a label/description, or empty. */
function docComment(text: string | null | undefined, depth: number): string {
  if (!text || !text.trim()) return "";
  const pad = "  ".repeat(depth);
  return `${pad}/** ${text.trim().replace(/\*\//g, "*\\/")} */\n`;
}

/** A safe object property key — bare identifier or quoted string literal. */
function propKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** Turn an arbitrary post-type name into a PascalCase identifier fragment. */
function pascalCase(name: string): string {
  const parts = (name ?? "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  let out = parts
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
  // A leading digit is not a valid identifier start.
  if (/^[0-9]/.test(out)) out = `T${out}`;
  return out;
}
