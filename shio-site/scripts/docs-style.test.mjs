// @scans prose reason: the subject is the documentation's Markdown read as writing, so the
// stripping it needs (frontmatter, fences, inline code, comments) is done here, line-preserving,
// to report each finding at the line a writer opens (SH1401).
//
// SH1401: a docs page judged as writing, not only as vocabulary.
//
// docs-vocabulary, docs-stack and docs-coverage prove that every name a page uses exists and that
// every shipped cluster has a page. Nothing read how a page is written, so pages grew one
// increment at a time. This lint holds the half of the shared `docs-writing` style guide that a
// machine can check (its reference/LINT-RULES.md); the judgement half lives in the
// `shio-docs-write` skill.
//
// The debt is a named list, BASELINE below, not a ceiling. The test fails when a page breaks a
// rule it is not listed for, and also when a listed page no longer breaks it: the list only
// shrinks, and the entry goes in the same change as the rewrite that paid it (SH1403-SH1409).
//
// Tuning is a list edit at the top of this file. A false positive is fixed by adding to
// PROPER_NOUNS or narrowing a phrase, never by adding a page to the baseline.

