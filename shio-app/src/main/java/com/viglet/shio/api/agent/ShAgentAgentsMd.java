package com.viglet.shio.api.agent;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.viglet.shio.api.agent.dto.ShAgentContext;
import com.viglet.shio.api.cda.dto.ShCdaSchemaField;

/**
 * Renders a context pack as an {@code AGENTS.md} (SH115) — project agent
 * instructions generated from the live instance instead of maintained by hand.
 *
 * <h2>Why generate it at all</h2>
 *
 * <p>A hand-written {@code AGENTS.md} that describes a content model is stale the
 * moment the model changes, and a stale instruction file is strictly worse than no
 * file: it costs tokens on every session <em>and</em> misleads. Generating it from
 * the same pack the protocol already serves means the file cannot drift from the
 * instance — regenerate it and the diff is the drift.</p>
 *
 * <h2>Why not just tell the agent to read the context pack</h2>
 *
 * <p>Because the two are read at different moments. The pack is a call an agent
 * makes once it has decided to work on content; {@code AGENTS.md} is loaded before
 * the agent has decided anything, by a harness that knows nothing about Shio. This
 * rendering is therefore instruction-shaped, not data-shaped: it opens with what to
 * do, and the model table exists to stop the agent inventing a post-type, not to be
 * a complete schema reference. The pack remains the authority, and the file says so.</p>
 *
 * <h2>Determinism</h2>
 *
 * <p>Byte-stable for a given pack (P5), and it carries the pack's {@code digest} so
 * a reviewer can tell at a glance whether a checked-in file still matches the
 * instance. Nothing here is measured — no token counts, no timestamps — because a
 * generated file that changes on every run is a generated file nobody commits.</p>
 *
 * @author Alexandre Oliveira
 * @since 2026.3
 */
public final class ShAgentAgentsMd {

    /** Fields listed per type before the line is cut. A model sketch, not a schema. */
    private static final int MAX_FIELDS_PER_TYPE = 12;

    private static final String MEMORY_PREFIX = "[memory:";

    private ShAgentAgentsMd() {
        // utility
    }

    public static String render(ShAgentContext pack) {
        StringBuilder out = new StringBuilder();
        header(out, pack);
        howToDriveIt(out);
        sites(out, pack);
        model(out, pack);
        tree(out, pack);
        conventions(out, pack);
        footer(out, pack);
        return out.toString();
    }

    private static void header(StringBuilder out, ShAgentContext pack) {
        ShAgentContext.Instance instance = pack.instance();
        out.append("# Working with this Shio instance\n\n");
        out.append("<!-- Generated by `shio context --as agents-md`. Do not edit by hand: ")
                .append("regenerate it and the diff is the drift. -->\n\n");
        if (instance != null) {
            out.append(instance.product());
            if (instance.version() != null) {
                out.append(" ").append(instance.version());
            }
            out.append(", protocol ").append(pack.protocol());
            if (instance.defaultLocale() != null) {
                out.append(", default locale `").append(instance.defaultLocale()).append("`");
            }
            out.append(".\n\n");
        }
    }

    /**
     * The opening move, in the order a session actually needs it. Kept to five lines
     * for the same reason the manifest's {@code startHere} is: a long list is a plan
     * the agent has to evaluate, a short one is an instruction it can follow.
     */
    private static void howToDriveIt(StringBuilder out) {
        out.append("## Start here\n\n");
        out.append("1. `GET /api/v2/agent/context?format=terse` — the model, the sitemap and "
                + "these conventions, live. **This file is a snapshot; that call is the "
                + "authority.** Send `If-None-Match` with the digest below and an unchanged "
                + "instance answers `304`.\n");
        out.append("2. Address content as `post:<site>/<friendly-url>` or "
                + "`folder:<site>/<folder-path>` — the home page is `post:<site>/`. "
                + "You never need a UUID; "
                + "`GET /api/v2/agent/resolve?address=…` produces one when an id-keyed "
                + "endpoint demands it.\n");
        out.append("3. Write with `POST /api/v2/agent/batch` (atomic, addressed, `dryRun`-able) "
                + "or declare an end state with `POST /api/v2/agent/apply`. Before modelling a "
                + "whole section by hand, check `GET /api/v2/agent/blueprints`.\n");
        out.append("4. Check your own work instead of asking: "
                + "`GET /api/v2/agent/verify?format=terse` and "
                + "`GET /api/v2/agent/render?address=…`.\n");
        out.append("5. When you work something out that the next session would re-derive, "
                + "record it: `shio remember <key> \"<note>\"`. It comes back in the "
                + "conventions below.\n\n");
    }

    private static void sites(StringBuilder out, ShAgentContext pack) {
        List<ShAgentContext.Site> sites = nullSafe(pack.sites());
        if (sites.isEmpty()) {
            return;
        }
        out.append("## Sites\n\n");
        for (ShAgentContext.Site site : sites) {
            out.append("- **").append(site.name()).append("** — ").append(site.posts())
                    .append(site.posts() == 1 ? " post" : " posts");
            if (site.url() != null && !site.url().isBlank()) {
                out.append(", served at ").append(site.url());
            }
            out.append("\n");
        }
        out.append("\n");
    }

    /**
     * The model as a table. Post counts are included on purpose: they are what
     * separates a load-bearing type from one somebody created and abandoned, and an
     * agent picking a type to write into needs that distinction more than it needs
     * the full field list.
     */
    private static void model(StringBuilder out, ShAgentContext pack) {
        List<ShAgentContext.Type> model = nullSafe(pack.model());
        if (model.isEmpty()) {
            return;
        }
        out.append("## Content model\n\n");
        out.append("Use one of these; do not invent a post-type. `!` marks a required field, "
                + "`[]` a multi-valued one.\n\n");
        out.append("| Post-type | Posts | Notes | Fields |\n");
        out.append("|---|---|---|---|\n");
        for (ShAgentContext.Type type : model) {
            out.append("| `").append(type.name()).append("` | ").append(type.posts())
                    .append(" | ").append(notes(type)).append(" | ")
                    .append(fields(type.fields())).append(" |\n");
        }
        out.append("\n");
    }

    private static String notes(ShAgentContext.Type type) {
        List<String> notes = new ArrayList<>();
        if (type.system()) {
            notes.add("system — cannot be modified");
        }
        if (type.managed()) {
            notes.add("managed by code — edit `shio/post-types/`, run `shio push`");
        }
        // SH768 — first, and in those words. This note is the whole point of the flag: a reader
        // meeting `ShioConfRendermsgmgaup2qjcArticle  TITLE, TEXT` in the model has no way to tell
        // a fixture from a decision somebody made, and reads it as a convention to follow.
        if (type.scratch()) {
            notes.add("SCRATCH — a fixture, not a convention; `shio post-type rm --scratch` sweeps it");
        }
        return notes.isEmpty() ? "—" : String.join("; ", notes);
    }

    private static String fields(List<ShCdaSchemaField> fields) {
        List<ShCdaSchemaField> all = nullSafe(fields);
        if (all.isEmpty()) {
            return "—";
        }
        List<String> rendered = new ArrayList<>();
        for (ShCdaSchemaField field : all.subList(0, Math.min(all.size(), MAX_FIELDS_PER_TYPE))) {
            rendered.add("`" + field.name() + (field.required() ? "!" : "")
                    + (field.multiple() ? "[]" : "") + "`");
        }
        if (all.size() > MAX_FIELDS_PER_TYPE) {
            // Says how many were cut rather than trailing off: an agent that knows the
            // list is partial reads the schema, one that does not assumes it is complete.
            rendered.add("… +" + (all.size() - MAX_FIELDS_PER_TYPE) + " more");
        }
        return String.join(" ", rendered);
    }

    /**
     * The folder skeleton — folders only, with their contents as counts.
     *
     * <p>Every individual page is deliberately left out. A generated instruction file
     * that lists content goes stale on the next publish and grows without bound;
     * {@code GET /api/v2/agent/find} answers "which pages" in one call and is always
     * current. What a session cannot cheaply guess is the <em>shape</em> of the tree,
     * so that is what this section carries.</p>
     */
    private static void tree(StringBuilder out, ShAgentContext pack) {
        Map<String, ShAgentContext.Node> folders = new LinkedHashMap<>();
        for (ShAgentContext.Node node : nullSafe(pack.sitemap())) {
            if ("folder".equals(node.kind())) {
                folders.putIfAbsent(node.path(), node);
            }
        }
        if (folders.isEmpty()) {
            return;
        }
        out.append("## Folder tree\n\n");
        out.append("```\n");
        for (ShAgentContext.Node folder : folders.values()) {
            out.append(folder.path());
            if (folder.posts() > 0) {
                out.append("  (").append(folder.posts()).append(" posts)");
            }
            out.append("\n");
        }
        out.append("```\n\n");
    }

    /**
     * Conventions, split into what the instance derives and what it was told.
     *
     * <p>The split is the point. A derived line is true by construction; a remembered
     * one is somebody's claim, and the reader deserves to know which is which before
     * acting on it. The marker is the {@code [memory:…]} prefix the context pack
     * already puts on remembered lines, so there is one encoding rather than two.</p>
     */
    private static void conventions(StringBuilder out, ShAgentContext pack) {
        List<String> all = nullSafe(pack.conventions());
        if (all.isEmpty()) {
            return;
        }
        List<String> derived = all.stream().filter(line -> !line.startsWith(MEMORY_PREFIX)).toList();
        List<String> remembered = all.stream().filter(line -> line.startsWith(MEMORY_PREFIX)).toList();

        if (!derived.isEmpty()) {
            out.append("## How this instance works\n\n");
            derived.forEach(line -> out.append("- ").append(line).append("\n"));
            out.append("\n");
        }
        if (!remembered.isEmpty()) {
            out.append("## Remembered decisions\n\n");
            out.append("Recorded by earlier sessions and by humans; the attribution is part of "
                    + "the claim.\n\n");
            remembered.forEach(line -> out.append("- ").append(line).append("\n"));
            out.append("\n");
        }
    }

    private static void footer(StringBuilder out, ShAgentContext pack) {
        if (pack.digest() != null) {
            out.append("---\n\nContext digest: `").append(pack.digest())
                    .append("` — pass it as `If-None-Match` to check this file is still current "
                            + "without paying for the pack.\n");
        }
    }

    private static <T> List<T> nullSafe(List<T> values) {
        return values == null ? List.of() : values;
    }
}
