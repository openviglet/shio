import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

// @scans prose — reason: the subject is a URL and two i18n keys as literal strings, in source and
// in JSON; nothing here reads a sentence as a claim about a rule (SH740).

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const SKIP = new Set(["node_modules", "target", "dist", "dist-ssr", "build", ".git", "store", ".roadkeep"]);

/**
 * SH954 — the Clear Cache button is gone, and so is the endpoint it lied through.
 *
 * `ShObjectAPI.clearCache` was a `@GetMapping("/{id}/clear-cache")` whose entire body was
 * `return ResponseEntity.ok().build();`. Its own javadoc said the page-cache subsystem it drove was
 * not part of the backend any more and that the no-op was "kept for the console's clear cache
 * action (it expects a 200)". The content browser rendered a **Clear Cache** button on every row,
 * called it, and toasted "Cache cleared" — so the product told a curator it had done something,
 * every time, for as long as the cache had been gone.
 *
 * Deleted rather than reimplemented: the CDA's cache-control headers and the image-transform cache
 * are invalidated by publishing, not by a row button. If an operator ever needs to purge derived
 * images, that is a named verb with a real effect and an agent equivalent — a line of its own, not
 * a resurrection of this one.
 *
 * `ShNoOpMappingLintTest` is the half that generalises: it fails on any mapping whose body is a
 * bare success. This is the narrow half — that this particular name is gone from every surface,
 * including the ones a Java lint cannot see.
 */

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (/\.(ts|tsx|mjs|js|java|json|md)$/.test(entry)) out.push(path);
  }
  return out;
}

/** Where a mention would still be a fact rather than a call: the history of having removed it. */
const HISTORY = /^(docs\/(CHANGELOG|IMPROVEMENTS|ROADMAP)\.md|docs\/agents\/|shio-react\/test\/clear-cache-gone\.test\.mjs|shio-app\/src\/test\/)/;

/**
 * The console bundle Vite writes into the backend's resources. Gitignored, regenerated by every
 * build, and stale on any machine that has not run one since the source changed — so a hit here
 * says when somebody last built, not what the product does.
 */
const GENERATED = /^shio-app\/src\/main\/resources\/public\//;

test("SH954: nothing calls clear-cache, and no key names it", () => {
  const offenders = [];
  let scanned = 0;

  for (const path of walk(ROOT)) {
    const relative = path.slice(ROOT.length).replace(/\\/g, "/");
    if (HISTORY.test(relative) || GENERATED.test(relative)) continue;
    scanned += 1;
    const text = readFileSync(path, "utf8");
    for (const needle of ["clear-cache", "clearCacheAction", "cacheCleared"]) {
      if (text.includes(needle)) offenders.push(`${relative} names ${needle}`);
    }
  }

  assert.ok(scanned > 400,
    `SH954: walked ${scanned} files, which is too few to have looked anywhere — the walk is broken`);

  assert.deepEqual(offenders, [],
    "SH954: the clear-cache action is gone, endpoint and button together. A surface that still "
    + "names it is either a caller of a route that no longer exists or a label for a button that "
    + "does not — and the second is how this survived: the endpoint was kept alive BECAUSE the "
    + "console called it.\n  " + offenders.join("\n  "));
});
